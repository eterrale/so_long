#include "libft.h"

void	*ft_memchr(const void *s, int c, size_t n)
{
	size_t	i;
	char	*src_cpy;

	src_cpy = (char *)s;
	i = 0;
	while (i++ < n)
	{
		if (*src_cpy == (char)c)
		{
			return (src_cpy);
		}
		src_cpy++;
	}
	return (NULL);
}
